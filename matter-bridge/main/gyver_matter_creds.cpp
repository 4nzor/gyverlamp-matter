CHIP_ERROR CopyCString(char *buf, size_t bufSize, const char *src)
{
    if (bufSize == 0) {
        return CHIP_ERROR_BUFFER_TOO_SMALL;
    }
    size_t n = strlen(src);
    if (n + 1 > bufSize) {
        return CHIP_ERROR_BUFFER_TOO_SMALL;
    }
    memcpy(buf, src, n + 1);
    return CHIP_NO_ERROR;
}

class TasmotaDacProvider : public DeviceAttestationCredentialsProvider
{
public:
    CHIP_ERROR GetCertificationDeclaration(MutableByteSpan &out_cd_buffer) override
    {
        return CopySpanToMutableSpan(ByteSpan{k_tasmota_cd}, out_cd_buffer);
    }

    CHIP_ERROR GetFirmwareInformation(MutableByteSpan &out_firmware_info_buffer) override
    {
        out_firmware_info_buffer.reduce_size(0);
        return CHIP_NO_ERROR;
    }

    CHIP_ERROR GetDeviceAttestationCert(MutableByteSpan &out_dac_buffer) override
    {
        return CopySpanToMutableSpan(ByteSpan{k_tasmota_dac_cert}, out_dac_buffer);
    }

    CHIP_ERROR GetProductAttestationIntermediateCert(MutableByteSpan &out_pai_buffer) override
    {
        return CopySpanToMutableSpan(ByteSpan{k_tasmota_pai_cert}, out_pai_buffer);
    }

    CHIP_ERROR SignWithDeviceAttestationKey(const ByteSpan &message_to_sign,
                                            MutableByteSpan &out_signature_buffer) override
    {
        Crypto::P256ECDSASignature signature;
        Crypto::P256Keypair keypair;

        VerifyOrReturnError(!out_signature_buffer.empty(), CHIP_ERROR_INVALID_ARGUMENT);
        VerifyOrReturnError(!message_to_sign.empty(), CHIP_ERROR_INVALID_ARGUMENT);
        VerifyOrReturnError(out_signature_buffer.size() >= signature.Capacity(), CHIP_ERROR_BUFFER_TOO_SMALL);

        ReturnErrorOnFailure(keypair.HazardousOperationLoadKeypairFromRaw(ByteSpan{k_tasmota_dac_priv},
                                                                            ByteSpan{k_tasmota_dac_pub}));
        ReturnErrorOnFailure(keypair.ECDSA_sign_msg(message_to_sign.data(), message_to_sign.size(), signature));
        return CopySpanToMutableSpan(ByteSpan{signature.ConstBytes(), signature.Length()}, out_signature_buffer);
    }
};

